def build_agent_prompt(extra_context: str | None = None) -> str:
    """Return the stable system prompt with optional bounded task context."""
    if not extra_context:
        return AGENT_SYSTEM_PROMPT
    return f"{AGENT_SYSTEM_PROMPT}\n【本次任务上下文】\n{extra_context.strip()}"
